    def _generate_suggestions(self, issues: List[Dict], ai_score: float) -> List[str]:
        """Generate general suggestions based on detected issues"""
        suggestions = []
        
        if ai_score > 0.5:
            suggestions.append("This code appears to be AI-generated. Consider reviewing for:")
            suggestions.append("- Completeness and functionality")
            suggestions.append("- Code quality and best practices")
            suggestions.append("- Security vulnerabilities")
            suggestions.append("- Performance optimizations")
        
        if any(issue['type'] == 'placeholder_comment' for issue in issues):
            suggestions.append("Replace placeholder comments with actual implementations")
        
        if any(issue['type'] == 'insufficient_comments' for issue in issues):
            suggestions.append("Add more descriptive comments to explain the code logic")
        
        if any(issue['type'] == 'generic_variable' for issue in issues):
            suggestions.append("Use more descriptive variable and function names")
        
        return suggestions

    def _generate_fixes(self, code: str, issues: List[Dict], language: str) -> List[Dict]:
        """Generate specific fixes for detected issues"""
        fixes = []
        
