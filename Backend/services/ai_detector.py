    def _semantic_analysis(self, code: str, language: str) -> List[Dict]:
        """Use SBERT for semantic similarity analysis of comments and code"""
        issues = []
        
        if not self.sbert_model:
            return issues

        try:
            # Extract comments from code
            comments = self._extract_comments(code, language)
            if not comments:
                return issues

            # Get embeddings for comments
            comment_embeddings = self.sbert_model.encode(comments)
            
            # Compare with known AI-generated comment patterns
            ai_comment_patterns = [
                "This function does something",
                "This method performs an operation",
                "This class represents a data structure",
                "This variable stores a value",
                "Add implementation here",
                "Insert logic here",
                "TODO: implement this",
                "Placeholder for future implementation"
            ]
            
            pattern_embeddings = self.sbert_model.encode(ai_comment_patterns)
            
            # Calculate similarities
            similarities = cosine_similarity(comment_embeddings, pattern_embeddings)
            
            for i, comment in enumerate(comments):
                max_similarity = np.max(similarities[i])
                if max_similarity > 0.8:  # High similarity threshold
                    issues.append({
                        "type": "semantic_similarity",
                        "message": f"Comment shows high similarity to AI-generated patterns: '{comment}'",
                        "line": self._find_comment_line(code, comment),
                        "severity": "medium",
                        "category": "ai_generated",
                        "suggestion": "Rewrite comment to be more specific and descriptive",
                        "fix": self._generate_semantic_fix(comment, language),
                        "confidence": max_similarity
                    })
        
        except Exception as e:
            print(f"Semantic analysis error: {e}")
        
        return issues

    def _nlp_comment_analysis(self, code: str, language: str) -> List[Dict]:
        """Use spaCy for advanced NLP analysis of comments"""
        issues = []
        
        if not self.nlp:
            return issues

        try:
            comments = self._extract_comments(code, language)
            
            for comment in comments:
                doc = self.nlp(comment)
                
                # Check for overly generic language
                generic_indicators = ['this', 'that', 'thing', 'stuff', 'something', 'anything']
                generic_count = sum(1 for token in doc if token.text.lower() in generic_indicators)
                
                if generic_count > 2:
                    issues.append({
                        "type": "generic_language",
                        "message": f"Comment uses overly generic language: '{comment}'",
                        "line": self._find_comment_line(code, comment),
                        "severity": "low",
                        "category": "ai_generated",
                        "suggestion": "Use more specific and descriptive language",
                        "fix": self._generate_nlp_fix(comment, language)
                    })
                
                # Check for lack of technical terms
                technical_terms = [token.text for token in doc if token.pos_ in ['NOUN', 'PROPN']]
                if len(technical_terms) < 2:
                    issues.append({
                        "type": "lack_technical_terms",
                        "message": f"Comment lacks technical specificity: '{comment}'",
                        "line": self._find_comment_line(code, comment),
                        "severity": "medium",
                        "category": "ai_generated",
                        "suggestion": "Include more technical terms and specific details",
                        "fix": self._generate_technical_fix(comment, language)
                    })
        
        except Exception as e:
            print(f"NLP analysis error: {e}")
        
        return issues

